package com.accutech.stocktaking.notify.model;

/**
 * 单条通知的最终判定结果。
 *
 * <p>每个责任人一定有一条结果，取值只有这五种 —— 排错时只要看 decision 就能知道
 * "发出去了 / 被闸门拦了 / 发失败了 / 只是演练 / 还在等群发"。</p>
 */
public enum NotifyDecision {

    /** 发送成功 */
    SEND,

    /** 跳过（未发送，原因见 reason） */
    SKIP,

    /** 发送失败（企微或链路异常，原因见 reason） */
    FAIL,

    /** 演练：只做判定与文案预览，不发送 */
    PREVIEW,

    /**
     * 已通过全部闸门、等待与同文案的人合并群发。
     *
     * <p>只允许在「判定完成 → 群发回写结果」之间的瞬间存在；
     * 群发结束后如果还有行停留在此状态，说明发送环节出了异常 ——
     * 汇总会按<b>失败</b>统计（而不是跳过），运维看到就能知道是发送环节出了问题。</p>
     */
    PENDING
}
